        "    def _grow_tree(self, X, Y, D, depth):\n",
        "        \"\"\"Recursively grow tree\"\"\"\n",
        "        n = len(Y)\n",
        "        \n",
        "        if depth >= self.max_depth or n < 2 * self.min_samples_leaf:\n",
