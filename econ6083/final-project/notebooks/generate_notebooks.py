        "    \"\"\"\n",
        "    Simplified Causal Tree implementation following Athey & Imbens (2016)\n",
        "    \"\"\"\n",
        "    \n",
        "    def __init__(self, max_depth=3, min_samples_leaf=20):\n",
        "        self.max_depth = max_depth\n",
        "        self.min_samples_leaf = min_samples_leaf\n",
        "        \n",
        "    def fit(self, X, Y, D):\n",
