        "                tau_right = self._treatment_effect(Y[right], D[right])\n",
        "                gain = abs(tau_left - tau_right)\n",
        "                \n",
        "                if gain > best_gain:\n",
        "                    best_gain = gain\n",
        "                    best_split = {'feature': feature, 'threshold': threshold}\n",
        "        \n",
        "        if best_split is None:\n",
