        "            thresholds = np.percentile(X[:, feature], [25, 50, 75])\n",
        "            for threshold in thresholds:\n",
        "                left = X[:, feature] <= threshold\n",
        "                right = ~left\n",
        "                \n",
        "                if left.sum() < self.min_samples_leaf or right.sum() < self.min_samples_leaf:\n",
