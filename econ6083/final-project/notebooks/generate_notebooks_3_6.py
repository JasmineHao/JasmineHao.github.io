        "def synthetic_control(Y_target, Y_donors):\n",
        "    \"\"\"\n",
        "    Find optimal weights w that minimize ||Y_target - Y_donors @ w||^2\n",
        "    Subject to: sum(w) = 1, w >= 0 (convex combination)\n",
        "    \n",
        "    Y_target: (T_pre,) pre-treatment outcomes for treated unit\n",
        "    Y_donors: (T_pre, J) pre-treatment outcomes for donor pool\n",
        "    \n",
        "    Returns: optimal weights (J,)\n",
        "    \"\"\"\n",
        "    n_donors = Y_donors.shape[1]\n",
        "    \n",
        "    # Objective: sum of squared errors\n",
        "    def objective(w):\n",
        "        return np.sum((Y_target - Y_donors @ w) ** 2)\n",
        "    \n",
        "    # Constraints: weights sum to 1 and are non-negative\n",
        "    constraints = {'type': 'eq', 'fun': lambda w: np.sum(w) - 1}\n",
        "    bounds = [(0, 1) for _ in range(n_donors)]\n",
        "    \n",
        "    # Optimize\n",
        "    result = minimize(\n",
        "        objective,\n",
        "        x0=np.ones(n_donors) / n_donors,\n",
        "        method='SLSQP',\n",
        "        bounds=bounds,\n",
        "        constraints=constraints\n",
        "    )\n",
        "    \n",
        "    return result.x\n",
