        "    \"\"\"\n",
        "    Run placebo test: apply SCM treating each donor as \"treated\"\n",
        "    \n",
        "    Returns: placebo effect estimates for each donor state\n",
        "    \"\"\"\n",
        "    pre_years = [y for y in df_wide.columns if y < treat_year]\n",
        "    post_years = [y for y in df_wide.columns if y >= treat_year]\n",
        "    \n",
        "    # Actual treated unit\n",
        "    Y_target = df_wide.loc[treat_state, pre_years].values\n",
        "    Y_donors = df_wide.loc[donor_states, pre_years].values.T\n",
        "    \n",
        "    # Get synthetic control weights\n",
        "    weights = synthetic_control(Y_target, Y_donors)\n",
        "    \n",
        "    # Compute post-treatment gaps for actual\n",
        "    gaps = []\n",
        "    for year in post_years:\n",
        "        actual = df_wide.loc[treat_state, year]\n",
        "        synthetic = np.sum(weights * df_wide.loc[donor_states, year].values)\n",
        "        gaps.append(actual - synthetic)\n",
        "    \n",
        "    return np.mean(gaps), weights\n",
