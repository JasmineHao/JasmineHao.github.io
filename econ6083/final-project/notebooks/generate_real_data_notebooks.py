        "        \n",
        "        if (D_train==1).sum() > 10:\n",
        "            rf1 = RandomForestRegressor(n_estimators=50, random_state=42)\n",
        "            rf1.fit(X_train[D_train==1], Y_train[D_train==1])\n",
        "            mu1[test_idx] = rf1.predict(X_test)\n",
        "        \n",
        "        # Propensity score\n",
